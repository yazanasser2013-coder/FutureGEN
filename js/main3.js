  const heroTitle = document.querySelector('.hero-title');
  if (heroTitle && heroTitle.getAttribute(langData)) {
    heroTitle.textContent = heroTitle.getAttribute(langData);
  }

  const heroSubtitle = document.querySelector('.hero-subtitle');
  if (heroSubtitle && heroSubtitle.getAttribute(langData)) {
    const counterSpan = heroSubtitle.querySelector('.counter');
    const textSpan = document.createElement('span');
    textSpan.textContent = heroSubtitle.getAttribute(langData);

    if (counterSpan) {
      heroSubtitle.innerHTML = '';
      heroSubtitle.appendChild(counterSpan);
      heroSubtitle.appendChild(document.createTextNode(' '));
      heroSubtitle.appendChild(textSpan);
    } else {
      heroSubtitle.textContent = heroSubtitle.getAttribute(langData);
    }
  }

  // تحديث أزرار الهيرو
  const exploreBtn = document.getElementById('exploreToolsBtn');
  if (exploreBtn && exploreBtn.getAttribute(langData)) {
    exploreBtn.textContent = exploreBtn.getAttribute(langData);
  }

  const browseBtn = document.getElementById('browseCategoriesBtn');
  if (browseBtn && browseBtn.getAttribute(langData)) {
    browseBtn.textContent = browseBtn.getAttribute(langData);
  }

  // تحديث عناوين الأقسام
  const categoriesTitle = document.querySelector('.categories-title');
  if (categoriesTitle && categoriesTitle.getAttribute(langData)) {
    categoriesTitle.textContent = categoriesTitle.getAttribute(langData);
  }

  const toolsTitle = document.querySelector('.Tools-title');
