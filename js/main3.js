function scrollToToolDetailsTop() {
  const detailsPage =
    document.getElementById('tool-details-page') ||
    document.querySelector('.tool-details-page');

  if (!detailsPage) {
    // fallback عام
    window.scrollTo({ top: 0, behavior: 'smooth' });
    return;
  }

  const header = document.querySelector('header, .header, .navbar, .topbar');
  const offset = header ? header.offsetHeight + 10 : 10;

  const top = detailsPage.getBoundingClientRect().top + window.scrollY - offset;
  window.scrollTo({ top, behavior: 'smooth' });
}

function scrollToToolDetailsTopForce() {
  const detailsPage =
    document.getElementById('tool-details-page') ||
    document.querySelector('.tool-details-page') ||
    document.querySelector('[data-page="tool-details-page"]');

  // لو ما لقينا صفحة التفاصيل، نسكرول الصفحة نفسها
  if (!detailsPage) {
    window.scrollTo({ top: 0, behavior: 'smooth' });
    return;
  }

  // ابحث عن أقرب عنصر عنده scroll داخلي فعلي
  let p = detailsPage;
  while (p && p !== document.body) {
    const s = getComputedStyle(p);
    const canScroll =
      (s.overflowY === 'auto' || s.overflowY === 'scroll') &&
      p.scrollHeight > p.clientHeight;

    if (canScroll) {
      p.scrollTo({ top: 0, behavior: 'smooth' });
      return;
    }
    p = p.parentElement;
  }

  // fallback: سكرول على window لموضع صفحة التفاصيل
  const header = document.querySelector('header, .header, .navbar, .topbar');
  const offset = header ? header.offsetHeight + 10 : 10;
  const top = detailsPage.getBoundingClientRect().top + window.scrollY - offset;
  window.scrollTo({ top, behavior: 'smooth' });
}

