function performSearch() {
  const searchTerm = document.getElementById('searchInput').value.trim().toLowerCase();

  if (!searchTerm) {
    // إذا كان البحث فارغاً، عرض جميع الأدوات
    displayToolsByCategories();
    return;
  }

  const container = document.getElementById('featured-tools-container');
  if (!container) return;

  // تصفية الأدوات بناءً على مصطلح البحث
  const filteredTools = aiTools.filter(tool =>
    tool.name.toLowerCase().includes(searchTerm) ||
    tool.description.toLowerCase().includes(searchTerm) ||
    (tool.desc_ar && tool.desc_ar.toLowerCase().includes(searchTerm)) ||
    tool.category.toLowerCase().includes(searchTerm) ||
    tool.tags.some(tag => tag.toLowerCase().includes(searchTerm))
  );

  container.innerHTML = '';

  if (filteredTools.length === 0) {
    container.innerHTML = `
            <div class="col-12 text-center py-5">
                <i class="fas fa-search fa-3x mb-3 text-muted"></i>
                <h4 class="text-muted">${currentLanguage === 'ar' ? 'لم يتم العثور على نتائج' : 'No results found'}</h4>
                <p class="text-muted">${currentLanguage === 'ar' ? 'حاول استخدام مصطلحات بحث مختلفة' : 'Try using different search terms'}</p>
            </div>
        `;
    return;
  }

  // عرض نتائج البحث
  const resultsGrid = document.createElement('div');
  resultsGrid.className = 'row g-4';

  filteredTools.forEach(tool => {
    const toolCard = createToolCard(tool);
    resultsGrid.appendChild(toolCard);
  });

  container.appendChild(resultsGrid);
}

