(function () {
  "use strict";


  const NEWS_JSON_PATH = "site/data/news.json";


  const IDS = {
    newsPage: "news-page",
    postPage: "blog-post-page",
    newsLink: "news-link",
    newsContainer: "blog-posts-container",


    postTitle: "blog-post-title",
    postCategory: "blog-post-category",
    postDate: "blog-post-date",
    postAuthor: "blog-post-author",
    postImage: "blog-post-image",
    postBody: "blog-post-body-container",
  };


  const STATE = {
    loaded: false,
    loading: false,
    posts: [],
    index: {},
    cursor: 0,
    pageSize: 6,
    io: null,
    selectedId: null,
  };


  function getLang() {
    const ls = (localStorage.getItem("lang") || "").toLowerCase();
    const w1 = (window.currentLang || "").toLowerCase();
    const w2 = (window.currentLanguage || "").toLowerCase();
    return (w1 || w2 || ls || "en") === "ar" ? "ar" : "en";
  }


  function esc(s = "") {
    return String(s).replace(/[&<>"']/g, (m) => ({
      "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;"
    }[m]));
  }


  // ✅ يمنع أي HTML من summary (وبالتالي يمنع أي img إضافي داخل النص)
  function stripToTextOnly(html) {
    const wrap = document.createElement("div");
    wrap.innerHTML = String(html || "");
    // احذف أي وسائط
    wrap.querySelectorAll("img, picture, figure, video, iframe, source").forEach(el => el.remove());
    return (wrap.textContent || "").trim();
  }


  // ✅ احصل على أول صورة موجودة داخل summary (لو post.image فاضي)
  function firstImgFromHtml(html) {
    const m = String(html || "").match(/<img\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/i);
    return m ? m[1] : "";
  }


  async function loadOnce() {
    if (STATE.loaded) return STATE.posts;
    if (STATE.loading) return STATE.posts;


    STATE.loading = true;
    try {
      const r = await fetch(NEWS_JSON_PATH, { cache: "no-store" });
      if (!r.ok) throw new Error("news.json HTTP " + r.status);
      const data = await r.json();
      const arr = Array.isArray(data) ? data : (Array.isArray(data?.items) ? data.items : []);
      STATE.posts = arr.filter(Boolean);


      // index by id (fallback index as string)
      STATE.index = {};
      STATE.posts.forEach((p, i) => {
        const id = (p && p.id != null) ? String(p.id) : String(i);
        p.__id = id;
        STATE.index[id] = p;
      });


      STATE.loaded = true;
      STATE.cursor = 0;
      return STATE.posts;
    } finally {
      STATE.loading = false;
    }
  }


  function ensureSentinel() {
    let s = document.getElementById("news-sentinel");
    if (s) return s;
    s = document.createElement("div");
    s.id = "news-sentinel";
    s.style.cssText = "height:1px;";
    const container = document.getElementById(IDS.newsContainer);
    if (container && container.parentElement) container.parentElement.appendChild(s);
    return s;
  }


  function renderBatch(reset = false) {
    const container = document.getElementById(IDS.newsContainer);
    if (!container) return;


    const lang = getLang();
    const posts = STATE.posts;


    if (reset) {
      container.innerHTML = "";
      STATE.cursor = 0;
    }


    const start = STATE.cursor;
    const end = Math.min(posts.length, start + STATE.pageSize);
    if (start >= end) return;


    const frag = document.createDocumentFragment();


    for (let i = start; i < end; i++) {
      const p = posts[i];
      if (!p) continue;


      const title = lang === "ar" ? (p.title_ar || p.title_en || "") : (p.title_en || p.title_ar || "");
      const category = lang === "ar" ? (p.category_ar || p.category_en || "AI") : (p.category_en || p.category_ar || "AI");
      const author = lang === "ar" ? (p.author_ar || p.author_en || "") : (p.author_en || p.author_ar || "");
      const date = p.date || "";


      const summaryRaw = lang === "ar"
        ? (p.summary_ar || p.summary_en || "")
        : (p.summary_en || p.summary_ar || "");


      // ✅ نص فقط = يمنع ظهور صورة ثانية داخل الكارت
      const cleanSummary = stripToTextOnly(summaryRaw);


      // ✅ صورة واحدة فقط: post.image أولاً، لو فاضية خذ أول img من summary
      const imgFromSummary = firstImgFromHtml(summaryRaw);
      const oneImage = (p.image && String(p.image).trim()) ? String(p.image).trim() : (imgFromSummary || "");


      const col = document.createElement("div");
      col.className = "col-12 col-md-6 col-lg-4";


      col.innerHTML = `
        <div class="card h-100 shadow-sm border-0 blog-card" style="overflow:hidden;border-radius:16px;">
          ${oneImage ? `
            <div style="height:200px;background:#f3f4f6;">
              <img loading="lazy"
                   src="${esc(oneImage)}"
                   alt="${esc(title)}"
                   style="width:100%;height:200px;object-fit:cover;display:block;"
                   onerror="this.style.display='none'">
            </div>
          ` : ``}
          <div class="card-body d-flex flex-column">
            <div class="d-flex justify-content-between align-items-center mb-2">
              <span class="badge bg-primary">${esc(category)}</span>
              <small class="text-muted">${esc(date)}</small>
            </div>
            <h5 class="card-title fw-bold" style="min-height:48px;">${esc(title)}</h5>
            <p class="card-text text-muted"
               style="flex:1;display:-webkit-box;-webkit-line-clamp:3;-webkit-box-orient:vertical;overflow:hidden;">
              ${esc(cleanSummary)}
            </p>
            <div class="d-flex justify-content-between align-items-center mt-3">
              <small class="text-muted">${esc(author)}</small>
              <button class="btn btn-outline-primary btn-sm" data-news-open="${esc(p.__id)}">
                ${lang === "ar" ? "اقرأ المزيد" : "Read more"}
              </button>
            </div>
          </div>
        </div>
      `;


      frag.appendChild(col);
    }


    container.appendChild(frag);
    STATE.cursor = end;


    // bind open
    container.querySelectorAll("button[data-news-open]").forEach(btn => {
      if (btn.__bound) return;
      btn.__bound = true;
      btn.addEventListener("click", () => openPost(btn.getAttribute("data-news-open")));
    });


    // stop io if finished
    if (STATE.cursor >= posts.length && STATE.io) {
      try { STATE.io.disconnect(); } catch (_) {}
      STATE.io = null;
    }
  }


  function setupInfiniteScroll() {
    const sentinel = ensureSentinel();
    if (!sentinel) return;


    if (STATE.io) {
      try { STATE.io.disconnect(); } catch (_) {}
      STATE.io = null;
    }


    STATE.io = new IntersectionObserver((entries) => {
      if (entries.some(e => e.isIntersecting)) renderBatch(false);
    }, { root: null, rootMargin: "600px 0px", threshold: 0.01 });


    STATE.io.observe(sentinel);
  }


  async function openNewsPageAndRender() {
  const newsPage = document.getElementById("news-page");
  if (!newsPage) return;

  // ✅ افتح صفحة الأخبار
  if (typeof showPage === "function") showPage("news-page");
  else newsPage.style.display = "block";

  // ✅ تحميل الأخبار مرة واحدة
  await loadNewsOnce();

  // ✅ ارسم الـ 60 كلها دفعة واحدة
  window.NEWS_PAGE_SIZE = 60;
  renderNewsBatch(true); // يرسم 60 لأنه يعتمد على NEWS_PAGE_SIZE
}





  function openPost(id) {
    const post = STATE.index[String(id)];
    if (!post) return;


    STATE.selectedId = String(id);


    const lang = getLang();
    const title = lang === "ar" ? (post.title_ar || post.title_en || "") : (post.title_en || post.title_ar || "");
    const category = lang === "ar" ? (post.category_ar || post.category_en || "") : (post.category_en || post.category_ar || "");
    const author = lang === "ar" ? (post.author_ar || post.author_en || "") : (post.author_en || post.author_ar || "");
    const body = lang === "ar" ? (post.body_ar || post.body_en || "") : (post.body_en || post.body_ar || "");


    const tEl = document.getElementById(IDS.postTitle);
    const cEl = document.getElementById(IDS.postCategory);
    const dEl = document.getElementById(IDS.postDate);
    const aEl = document.getElementById(IDS.postAuthor);
    const iEl = document.getElementById(IDS.postImage);
    const bEl = document.getElementById(IDS.postBody);


    if (tEl) tEl.textContent = title;
    if (cEl) cEl.textContent = category;
    if (dEl) dEl.textContent = post.date || "";
    if (aEl) aEl.textContent = author;


    // ✅ حذف صورة الهيدر الكبيرة نهائياً (في العربي والإنجليزي)
    if (iEl) {
      iEl.src = "";
      iEl.style.display = "none";
    }


    // ✅ (اختياري) لو body فيه صور كثيرة هذا طبيعي — نحن فقط حذفنا الهيدر
    if (bEl) bEl.innerHTML = String(body || "");


    // navigate
    if (typeof window.showPage === "function") {
      window.showPage(IDS.postPage);
    } else {
      document.querySelectorAll(".page").forEach(p => p.style.display = "none");
      const pg = document.getElementById(IDS.postPage);
      if (pg) pg.style.display = "block";
    }
  }


  // expose globals (لو كودك يناديها)
  window.openNewsPageAndRender = openNewsPageAndRender;
  window.__NEWS_RENDER_BATCH__ = () => renderBatch(true);
  window.__NEWS_OPEN_POST__ = openPost;


  // ✅ ربط news-link مرة واحدة (capture) عشان يغلب الرواتر القديم
  document.addEventListener("click", async (e) => {
    const link = e.target.closest("#" + IDS.newsLink);
    if (!link) return;


    e.preventDefault();
    e.stopImmediatePropagation();


    if (typeof window.showPage === "function") window.showPage(IDS.newsPage);
    else {
      document.querySelectorAll(".page").forEach(p => p.style.display = "none");
      const pg = document.getElementById(IDS.newsPage);
      if (pg) pg.style.display = "block";
    }


    try { await openNewsPageAndRender(); } catch (err) { console.error(err); }
  }, true);


  // ✅ عند تغيير اللغة: لو أنت داخل الأخبار/المقال أعد العرض بدون fetch
  document.addEventListener("click", (e) => {
    const btn = e.target.closest("#langToggle");
    if (!btn) return;


    const newsPage = document.getElementById(IDS.newsPage);
    const postPage = document.getElementById(IDS.postPage);


    const onNews = newsPage && newsPage.style.display !== "none";
    const onPost = postPage && postPage.style.display !== "none";


    if (onNews && STATE.loaded) {
      renderBatch(true);
      setupInfiniteScroll();
    }
    if (onPost && STATE.selectedId) {
      openPost(STATE.selectedId);
    }
  }, true);


})();